const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const vm = require('node:vm');
const source = fs.readFileSync(require.resolve('./admin-draft-stock.ts'), 'utf8');
const code = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
const sandbox = { exports: {}, require };
vm.runInNewContext(code, sandbox);
const warning = sandbox.exports.getAdminDraftLineStockWarning;
const product = { id: 'fixture-product', stockCount: 4, inStock: true, variants: [] };
const line = { quantity: 5, stockProduct: product, fallbackPrice: 33, lineDiscountValue: '20' };
const initial = JSON.stringify(line);
assert.ok(warning(line).includes('Plus que 4 en stock'));
assert.equal(warning({ ...line, quantity: 4 }), null);
assert.equal(warning({ ...line, isCustomItem: true }), null);
assert.equal(warning({ quantity: 5 }), null);
assert.ok(warning({ ...line, stockProduct: { ...product, inStock: false } }).includes('Rupture'));
assert.equal(warning({ ...line, stockProduct: { ...product, stockCount: null } }), null);
const variant = { id: 'fixture-variant', stock: 2, inStock: true };
assert.ok(warning({ ...line, variantId: variant.id }, [variant]).includes('Plus que 2 en stock'));
assert.equal(JSON.stringify(line), initial);
const page = fs.readFileSync(require.resolve('../app/admin/commandes/brouillons/page.tsx'), 'utf8');
assert.ok(page.includes('stockProduct: (item as OrderItem & { product?: Product }).product'));
assert.ok(!page.includes('product: (item as OrderItem & { product?: Product }).product,'));
assert.ok(page.includes('getAdminDraftLineStockWarning'));
assert.ok(page.includes('if (stockWarnings.length)'));
assert.ok(page.includes('draftId === editingId && stockWarnings.length'));
console.log('Tests stock admin frontend : lignes, stock/variantes, messages et prix du brouillon préservés.');
